def detect(s):
    """在句子里找句型，返回 [(pid, (plain_start, plain_end))]"""
    plain = s.get("plain", "")
    words = s.get("words", [])
    out = []
    for p in PATTERNS:
        pid, rule = p[0], p[5]
        kind = rule[0]
        if kind == "rx":
            for m in re.finditer(rule[1], plain):
                if m.end() > m.start():
                    out.append((pid, (m.start(), m.end())))
        elif kind == "pos":
            surf, pos0 = rule[1], rule[2]
            for w in words:
                if w["w"] == surf and (w.get("p") or "").startswith(pos0):
                    out.append((pid, (w["ps"], w["pe"])))
        elif kind == "pos2":
            surf, pos0, n = rule[1], rule[2], rule[3]
            for i in range(len(words) - n + 1):
                grp = words[i:i + n]
                if grp[0]["w"] != surf or not (grp[0].get("p") or "").startswith(pos0):
                    continue
                if rule[1] == "まし" and not (grp[1]["w"] == "た"):
                    continue
                if rule[1] == "ませ":
                    if not (grp[1]["w"] == "ん"):
                        continue
                    if n == 4 and not (grp[2]["w"] == "でし" and grp[3]["w"] == "た"):
                        continue
                out.append((pid, (grp[0]["ps"], grp[-1]["pe"])))
    return out


def build(episodes, subs_all):
    """扫全语料，为每个句型挑真实例句"""
    res = {}
    hits = {p[0]: [] for p in PATTERNS}
    for epi, ep in enumerate(episodes):
        for ver, cues in subs_all.get(ep["id"], {}).items():
            for i, c in enumerate(cues):
                for pid in set(g[2] for g in c.get("g", [])):
                    hits.setdefault(pid, []).append((epi + 1, ver, i, c))
    for p in PATTERNS:
        pid = p[0]
        h = hits.get(pid, [])
        ex, seen = [], set()
        for (epn, ver, i, c) in h:
            key = c["ja"][:24]
            if key in seen:
                continue
            seen.add(key)
            ex.append({"ja": c["ja"], "zh": c.get("zh", ""), "ep": epn, "i": i})
            if len(ex) >= 2:
                break
        res[pid] = {"n": p[1], "c": p[2], "m": p[3], "f": p[4], "k": len(h), "ex": ex}
    return res


