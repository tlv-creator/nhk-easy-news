#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gs_text.py —— gs 校验共用的**文本归一化**（唯一权威）。

🔴 为什么需要（2026-10-24 实测）：
   校验器用 `s not in ja` 判「幻觉」，但 MiniMax 偶尔会把全角标点写成半角
   （「貯金、していますか?」vs 原句「貯金、していますか？」）⇒ **被误判成幻觉而丢弃**。
   ⇒ 归一化必须先做。

🔴🔴 **铁律：归一化必须保持字符串长度不变**。
   原因：gs 的每个片段都带**字符位置**（frame[i].p / blocks[i].parts[j].p），
   而位置是在**原句**上算的。
   ⇒ 如果归一化把 1 个字符换成 2 个（如「？」→「?」→ 问号+空格），
      后面所有位置全部偏移 ⇒ 位置字段集体失真。
   ⇒ 所以只做**等长**映射（全角标点 → 半角标点都是 1 字符 → 1 字符），
      绝不做「删除」类操作。

🔴 同时提供「严格模式」给真正需要逐字一致的场合（如复制整句）。
"""

# ── 等长标点映射（全角 → 半角，1 字符 → 1 字符）──────────────────
_PUNCT_MAP = {
    "？": "?",   # ？
    "。": ".",   # 。
    "、": ",",   # 、
    "！": "!",   # ！
    "：": ":",   # ：
    "；": ";",   # ；
    "（": "(",   # （
    "）": ")",   # ）
    "「": "\"",  # 「
    "」": "\"",  # 」
    "・": "·",   # ・
    "−": "-",   # −
    "～": "~",   # ～
    "　": " ",   # 全角空格
}
# ⚠️ 语义括号（【】〔〕〈〉［］[]）**不归一化** —— 它们是 gs 的语义标记。

_LEN_CHECKED = True


def norm(s):
    """等长归一化：全角标点 → 半角；全角空格 → 半角空格。长度保持不变。"""
    t = (s or "")
    if not t:
        return ""
    out = "".join(_PUNCT_MAP.get(ch, ch) for ch in t)
    if _LEN_CHECKED and len(out) != len(t):
        # 🔴 兜底：万一将来加了不等长映射，宁可不动也不要改长度
        return t
    return out


def same_text(a, b):
    """两段文本在归一化后是否一致（用于「逐字一致」类断言）。"""
    return norm(a) == norm(b)


def contains(hay, needle):
    """needle 是否出现在 hay 中（归一化后比较；长度相等 ⇒ 位置仍可直接用）。"""
    h, n = norm(hay), norm(needle)
    if not n:
        return False
    return n in h


# ── 清洗：模型偶尔把「候选编号」写进译文（[2] [3]）──────────────
import re as _re

_CAND_MARK = _re.compile(r"\[[0-9]{1,2}\]")


def clean_zh_marks(s):
    """去掉译文里的候选编号标记（[2] [3] …）。

    🔴 实测（2026-10-24）：模型在「直接拼接候选[2][3]」时会把编号一并写进译文
       ⇒ 字符集合校验会误判成「多出字符」⇒ 实际只是格式问题。
    """
    return _CAND_MARK.sub("", s or "").strip()
